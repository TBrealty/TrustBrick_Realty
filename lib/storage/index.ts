import "server-only";
import { createReadStream, createWriteStream } from "node:fs";
import { mkdir, rm, stat } from "node:fs/promises";
import path from "node:path";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";

/**
 * Object storage. PostgreSQL holds media metadata only (D8); bytes live here.
 *
 * The local driver writes files under STORAGE_LOCAL_DIR (default `.data/storage`, git-ignored).
 * In production it only runs when STORAGE_LOCAL_DIR is set explicitly, which is the operator
 * saying "this path is a persistent volume"; otherwise it refuses rather than silently writing
 * to an ephemeral disk. Multi-server deployments need an S3-compatible driver implementing the
 * same interface.
 */
export interface StorageDriver {
  readonly provider: "local" | "s3";
  put(key: string, body: Buffer): Promise<void>;
  putStream(key: string, body: NodeJS.ReadableStream): Promise<void>;
  read(key: string): Promise<{ stream: ReadableStream; size: number } | null>;
  remove(keys: string[]): Promise<void>;
}

/** Keys are generated by the server only: lowercase path segments of safe characters. */
const SAFE_KEY = /^[a-z0-9][a-z0-9/_.-]{0,300}$/;

function assertSafeKey(key: string) {
  if (!SAFE_KEY.test(key) || key.includes("..") || key.includes("//")) throw new Error(`unsafe storage key: ${key}`);
}

class LocalDriver implements StorageDriver {
  readonly provider = "local" as const;
  constructor(private readonly root: string) {}

  private resolve(key: string) {
    assertSafeKey(key);
    const full = path.resolve(this.root, key);
    if (!full.startsWith(path.resolve(this.root) + path.sep)) throw new Error("storage key escapes root");
    return full;
  }

  async put(key: string, body: Buffer) {
    const full = this.resolve(key);
    await mkdir(path.dirname(full), { recursive: true });
    await pipeline(Readable.from(body), createWriteStream(full));
  }

  async putStream(key: string, body: NodeJS.ReadableStream) {
    const full = this.resolve(key);
    await mkdir(path.dirname(full), { recursive: true });
    await pipeline(body, createWriteStream(full));
  }

  async read(key: string) {
    const full = this.resolve(key);
    try {
      const info = await stat(full);
      if (!info.isFile()) return null;
      return { stream: Readable.toWeb(createReadStream(full)) as ReadableStream, size: info.size };
    } catch {
      return null;
    }
  }

  async remove(keys: string[]) {
    await Promise.all(keys.map((key) => rm(this.resolve(key), { force: true })));
  }
}

let driver: StorageDriver | null = null;

export function storage(): StorageDriver {
  if (driver) return driver;
  const kind = process.env.STORAGE_DRIVER ?? "local";
  if (kind !== "local") throw new Error(`Storage driver "${kind}" is not implemented yet. See lib/storage/index.ts.`);
  if (process.env.NODE_ENV === "production" && !process.env.STORAGE_LOCAL_DIR) {
    throw new Error("Local storage in production needs STORAGE_LOCAL_DIR pointing at a persistent volume, or an object-storage driver.");
  }
  driver = new LocalDriver(path.resolve(process.env.STORAGE_LOCAL_DIR ?? ".data/storage"));
  return driver;
}

/** Public URL path for a stored object. Served by app/media/[...key]/route.ts. */
export const mediaUrl = (key: string) => `/media/${key}`;
