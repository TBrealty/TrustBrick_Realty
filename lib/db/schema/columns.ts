import { sql } from "drizzle-orm";
import { customType, numeric, text, timestamp, uuid } from "drizzle-orm/pg-core";
import { v7 as uuidv7 } from "uuid";

/**
 * Column conventions shared by every schema (docs/database/04-tables.md):
 * UUIDv7 keys, timestamptz, numeric money, and the Postgres types Drizzle
 * does not ship with (citext, ltree, PostGIS geography, tsvector, tstzrange).
 */

export const id = () =>
  uuid("id")
    .primaryKey()
    .$defaultFn(() => uuidv7());

export const timestamps = {
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true })
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date()),
};

export const deletedAt = () => timestamp("deleted_at", { withTimezone: true });

/**
 * Human-friendly reference, e.g. `PRP-7K4M9Q2X`: generated by the database from 40 random bits,
 * unique, and made immutable by a trigger. An identifier, never an authorization.
 * The prefix is interpolated raw, so it must be a literal from REFERENCE_PREFIXES.
 */
export const referenceId = (prefix: ReferencePrefix) =>
  text("reference_id")
    .notNull()
    .unique()
    .default(sql.raw(`platform.gen_reference_id('${prefix}')`));

export const REFERENCE_PREFIXES = [
  "USR", "AGT", "ADM", "SADM", "ORG", "PRP", "LST", "PROJ", "LEAD", "VIS", "VER", "RPT", "INV", "CON", "DOC", "MSG", "TXN", "HST", "BKG", "TKT", "LGL", "COM", "SUB",
] as const;
export type ReferencePrefix = (typeof REFERENCE_PREFIXES)[number];

/** Money: numeric(16,2), read back as a JS number. Never a float column. */
export const money = (name: string) => numeric(name, { precision: 16, scale: 2, mode: "number" });

export const area = (name: string) => numeric(name, { precision: 10, scale: 2, mode: "number" });

/** Case-insensitive text. */
export const citext = customType<{ data: string }>({ dataType: () => "citext" });

/** Materialised hierarchy path, e.g. `in.telangana.hyderabad.gachibowli`. */
export const ltree = customType<{ data: string }>({ dataType: () => "ltree" });

/**
 * A WGS84 point stored as PostGIS geography, so distances come back in metres.
 * Read as GeoJSON-free WKB hex; write with ST_MakePoint in SQL.
 */
export const geographyPoint = customType<{ data: string }>({ dataType: () => "geography(Point,4326)" });

export const tsvector = customType<{ data: string }>({ dataType: () => "tsvector" });

export const tstzrange = customType<{ data: string }>({ dataType: () => "tstzrange" });

/** A range of calendar days, half-open: `[check-in, check-out)`, so back-to-back stays never overlap. */
export const daterange = customType<{ data: string }>({ dataType: () => "daterange" });
